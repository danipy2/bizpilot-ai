"""
BizPilot AI — Invoice Generation Tool
Agent tool for generating PDF invoices.
"""

import os
from datetime import datetime
from langchain.tools import tool

import config


@tool
def generate_invoice(
    customer_name: str,
    items: str,
    notes: str = "",
) -> str:
    """
    Generate a PDF invoice for a customer.
    Use this tool when the user asks to create, generate, or make an invoice.

    Args:
        customer_name: Name of the customer.
        items: Comma-separated list of items in format "item_name:quantity:unit_price".
              Example: "Laptop Dell:2:45000,Wireless Mouse:5:800"
        notes: Optional notes to include on the invoice.

    Returns:
        Confirmation message with the invoice file path and summary.
    """
    try:
        from fpdf import FPDF
    except ImportError:
        return "Error: fpdf2 is not installed. Run: pip install fpdf2"

    # Parse items
    parsed_items = []
    total = 0
    for item_str in items.split(","):
        parts = item_str.strip().split(":")
        if len(parts) != 3:
            return f"Error: Invalid item format '{item_str}'. Use 'name:quantity:unit_price'"
        name, qty, price = parts[0].strip(), int(parts[1].strip()), float(parts[2].strip())
        line_total = qty * price
        total += line_total
        parsed_items.append({
            "name": name,
            "quantity": qty,
            "unit_price": price,
            "line_total": line_total,
        })

    # Generate invoice number
    invoice_num = f"INV-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    invoice_date = datetime.now().strftime("%B %d, %Y")

    # Create PDF
    pdf = FPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Header
    pdf.set_font("Helvetica", "B", 24)
    pdf.cell(0, 15, "INVOICE", ln=True, align="C")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 8, "BizPilot AI — Business Automation", ln=True, align="C")
    pdf.ln(10)

    # Invoice details
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(95, 7, f"Invoice #: {invoice_num}")
    pdf.cell(95, 7, f"Date: {invoice_date}", ln=True)
    pdf.cell(95, 7, f"Bill To: {customer_name}", ln=True)
    pdf.ln(10)

    # Table header
    pdf.set_fill_color(52, 73, 94)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(80, 10, "Item", border=1, fill=True)
    pdf.cell(30, 10, "Qty", border=1, align="C", fill=True)
    pdf.cell(40, 10, "Unit Price (ETB)", border=1, align="C", fill=True)
    pdf.cell(40, 10, "Total (ETB)", border=1, align="C", fill=True, ln=True)

    # Table rows
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Helvetica", "", 10)
    for item in parsed_items:
        pdf.cell(80, 9, item["name"], border=1)
        pdf.cell(30, 9, str(item["quantity"]), border=1, align="C")
        pdf.cell(40, 9, f"{item['unit_price']:,.2f}", border=1, align="C")
        pdf.cell(40, 9, f"{item['line_total']:,.2f}", border=1, align="C", ln=True)

    # Total
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(150, 12, "TOTAL:", border=1, align="R")
    pdf.cell(40, 12, f"{total:,.2f} ETB", border=1, align="C", ln=True)

    # VAT (15%)
    vat = total * 0.15
    grand_total = total + vat
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(150, 9, "VAT (15%):", border=1, align="R")
    pdf.cell(40, 9, f"{vat:,.2f} ETB", border=1, align="C", ln=True)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(150, 12, "GRAND TOTAL:", border=1, align="R", fill=True)
    pdf.cell(40, 12, f"{grand_total:,.2f} ETB", border=1, align="C", fill=True, ln=True)

    # Notes
    if notes:
        pdf.ln(10)
        pdf.set_font("Helvetica", "I", 9)
        pdf.cell(0, 7, f"Notes: {notes}", ln=True)

    # Footer
    pdf.ln(15)
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(0, 5, "Generated by BizPilot AI — Intelligent Business Automation Agent", ln=True, align="C")

    # Save PDF
    filename = f"{invoice_num}.pdf"
    filepath = str(config.OUTPUT_DIR / filename)
    pdf.output(filepath)

    # Return summary (note: on Render the file is on server, so show full details in chat)
    items_summary = "\n".join(
        f"  • {item['name']}: {item['quantity']} × {item['unit_price']:,.2f} = {item['line_total']:,.2f} ETB"
        for item in parsed_items
    )

    return (
        f"✅ Invoice generated successfully!\n\n"
        f"📄 Invoice #: {invoice_num}\n"
        f"👤 Customer: {customer_name}\n"
        f"📅 Date: {invoice_date}\n\n"
        f"Items:\n{items_summary}\n\n"
        f"💰 Subtotal:    {total:,.2f} ETB\n"
        f"💰 VAT (15%):   {vat:,.2f} ETB\n"
        f"💰 Grand Total: {grand_total:,.2f} ETB\n\n"
        f"📁 PDF saved on server as: {filename}\n"
        f"💡 Share the above invoice summary with your customer."
    )
